export const presetById = (id) =>
  MAIL_PRESETS.find((preset) => preset.id === id) || MAIL_PRESETS[MAIL_PRESETS.length - 1];

export const PRESET_GROUPS = MAIL_PRESETS.reduce((groups, preset) => {
  const found = groups.find((g) => g.label === preset.group);
  if (found) found.items.push(preset);
  else groups.push({ label: preset.group, items: [preset] });
  return groups;
}, []);